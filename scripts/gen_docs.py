def checkpoint_doc(n):
    out = [f'<h1>{TITLES[n]}</h1>', '<p><b>Наша компания:</b> </p>']
    out += [x if x.startswith('<') else f'<p>{x}</p>' for x in INTRO[n]]
    if n == 1:
        out.append('<h2>Команда</h2>')
        out.append(tbl(['Роль', 'Имя'], [['Strategic Growth', ''], ['Acquisition', ''], ['Conversion', ''], ['Growth Finance', ''], ['Competitive Intelligence & Partnerships', ''], ['Второй Acquisition, если вас шестеро', '']]))
    if n == 2:
        out.append('<h2>Ответный ход</h2>')
        out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
            ['Против кого ходим (одна компания)', 'Competitive Intelligence', req(), ''],
            ['Что он сделал в чекпоинте 1, что нам угрожает', 'Competitive Intelligence', req(), ''],
            ['Что делаем в ответ. Конкретно: сегмент, канал, оффер, цена или карточка', 'Strategic Growth', req(), '']]))
    if n == 3:
        out.append('<h2>Что мы поняли из симуляции 1</h2>')
        out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
            ['Что сработало и что нет. 2-3 предложения', 'Growth Finance', req(), ''],
            ['Что меняем в этом ходе и почему', 'Strategic Growth', req(), '']]))
    out += open_part(n)
    out += closed_part(n)
    if n == 2:
        out.append('<h2>Прогноз</h2>')
        out.append('<p>' + opt() + '. Сколько пользователей будет у каждой компании после симуляции 1. Команда с самым точным прогнозом получает +5 баллов к итогу.</p>')
        out.append(tbl(['Компания', 'Пользователей после симуляции 1'], [[c['name'], ''] for c in COMPANIES]))
    if n == 3:
        out.append('<h2>Заметки для питча</h2>')
        out.append('<p>' + opt() + '. Питч идёт 3 минуты без презентации. Расскажите, что вы сделали за три хода, почему именно так и что поменяли бы сейчас.</p>')
        out.append(tbl(['Заметки'], [['']]))
    out.append('<h1>Как сдать ход</h1>')
    out.append(send_steps(n))
    return page('\n'.join(out))

