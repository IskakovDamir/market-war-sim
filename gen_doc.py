import os as _os; BASE = _os.path.dirname(_os.path.abspath(__file__))
import sys; sys.path.insert(0,BASE)
from spec import SEGMENTS, COMPANIES, CHANNELS, ACTIONS
R = '#F5000D'
def req(): return f'<b><span style="color:{R}">Обязательно</span></b>'
def opt(): return '<b>По желанию</b>'
def tbl(head, rows, widths=None):
    h = ''.join(f'<th style="text-align:left;background:#F2F2F2">{x}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table border="1" cellpadding="6" style="border-collapse:collapse;width:100%"><tr>{h}</tr>{b}</table>'
def k(n): return f'${n//1000:,}k'.replace(',', ' ')
seg_names = ', '.join(s['name'] for s in SEGMENTS)

def checkpoint(n):
    title = {1: 'Чекпоинт 1. Выход на рынок (квартал 1)',
             2: 'Чекпоинт 2. Ответ конкурентам (квартал 2)',
             3: 'Чекпоинт 3. Финальный ход (квартал 3)'}[n]
    intro = {1: 'Вы выходите на рынок. Ход зависит от вашей компании, бюджета и карты рынка.',
             2: 'Вы уже видели дашборд с ходами соперников. Теперь отвечаете им. Можно договариваться с другими командами о партнёрстве и покупке компании.',
             3: 'Вы видели первую симуляцию: сколько пользователей у каждой компании. Это последний ход. После него ментор запускает финальную симуляцию по выручке.'}[n]
    out = [f'<h1>{title}</h1>', f'<p>{intro}</p>']
    if n == 3:
        out.append('<h2>Что мы поняли из симуляции 1</h2>')
        out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
            ['Что сработало и что нет. 2-3 предложения', 'Growth Finance', req(), ''],
            ['Что меняем в этом ходе и почему', 'Strategic Growth', req(), '']]))
    if n == 2:
        out.append('<h2>Ответный ход</h2>')
        out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
            ['Против кого ходим (одна компания)', 'Competitive Intelligence', req(), ''],
            ['Что он сделал в чекпоинте 1, что нам угрожает', 'Competitive Intelligence', req(), ''],
            ['Что делаем в ответ. Конкретно: сегмент, канал, оффер, цена или карточка', 'Strategic Growth', req(), '']]))
    out.append('<h2>Открытая часть. Это увидят все команды на дашборде</h2>')
    out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
        ['Позиционирование. Одна фраза: «Для [кого] мы лучший выбор, потому что [результат], в отличие от [альтернатива]». Если меняете позиционирование, симуляция штрафует: покупатели хуже запоминают компанию', 'Strategic Growth', req(), ''],
        ['Главная реклама: текст объявления, до 25 слов. Продаём результат, а функции оставляем на потом', 'Conversion', req(), ''],
        ['Реклама: что на картинке или в видео, одна строка', 'Conversion', opt(), ''],
        ['Первый экран сайта: заголовок', 'Conversion', req(), ''],
        ['Первый экран сайта: подзаголовок и текст кнопки', 'Conversion', req(), ''],
        ['Публичное заявление: анонс, новость, партнёрство', 'Competitive Intelligence', opt(), '']]))
    out.append('<p><b>Тарифы.</b> До 3 тарифов. Цена в долларах в месяц. Бесплатный тариф ставьте с ценой $0. Заполняют Conversion и Growth Finance. ' + req() + '</p>')
    out.append(tbl(['Тариф', 'Цена в месяц', 'Что входит'], [['', '', ''], ['', '', ''], ['', '', '']]))
    out.append('<h2>Закрытая часть. Это видит только ментор</h2>')
    rows = []
    if n == 1:
        rows.append(['ICP: главный сегмент, один из пяти: ' + seg_names + '. Почему именно он. Для Rork этот сегмент становится целью на всю игру, менять его нельзя', 'Strategic Growth', req(), ''])
    else:
        rows.append(['ICP: остаётся тем же или меняется? Если меняется, на какой и почему', 'Strategic Growth', req(), ''])
    rows.append(['Тип войны: защита, атака на лидера, своя ниша или захват одного сегмента. Против кого и в чём', 'Strategic Growth', req(), ''])
    out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], rows))
    out.append('<p><b>Бюджет по каналам на этот квартал.</b> Заполняет Acquisition. ' + req() +
               '. Пишите сумму в долларах. Пустая строка значит $0. Ставка ниже минимальной работает только на 30%. Диапазоны цен за пользователя есть в справочнике в конце документа.</p>')
    out.append(tbl(['Канал', 'Минимальная ставка', 'Когда работает', 'Сумма, $'],
                   [[c['name'], k(c['min_k'] * 1000), c['when'].split(':')[0], ''] for c in CHANNELS] + [['<b>Итого на каналы</b>', '', '', '']]))
    out.append('<p><b>Карточки действий в этом квартале.</b> ' + opt() + '. Названия и цены есть в справочнике. Для атаки, копии фичи и эксклюзивного партнёра укажите соперника и сегмент.</p>')
    out.append(tbl(['Карточка', 'Соперник и сегмент, если нужно', 'Стоимость, $'], [['', '', ''], ['', '', ''], ['', '', '']]))
    out.append(tbl(['Поле', 'Кто', 'Статус', 'Ответ'], [
        ['Своё действие: что делаете, сколько стоит (минимум $20k), на какую готовую карточку похоже', 'Strategic Growth', opt(), ''],
        ['Сделка с другой командой: с кем, что делаете вместе, условия. Засчитывается, только если та же сделка записана в документе второй команды', 'Competitive Intelligence', opt(), ''] +
        ([] if n != 2 else []),
    ] + ([['Покупка компании (M&A): кого покупаем или кто покупает нас, цена. Минимум 3 квартальные выручки покупаемой. Тоже должна быть записана у обеих команд', 'Strategic Growth', opt(), '']] if n >= 2 else [])))
    out.append('<p><b>Экономика хода.</b> Заполняет Growth Finance. ' + req() + '</p>')
    out.append(tbl(['Показатель', 'Значение'], [
        ['Тратим в этом квартале всего (каналы плюс карточки), $', ''],
        ['Останется бюджета после квартала, $', ''],
        ['Ожидаемый CAC: сколько стоит один платящий клиент, $', ''],
        ['Ожидаемый LTV: сколько клиент принесёт за всё время, $', ''],
        ['Окупаемость CAC, месяцев', '']]))
    return '\n'.join(out)

company_rows = []
for c in COMPANIES:
    paid = sum(c['paid'].values()); mrr = paid * c['price']
    company_rows.append([f"<b>{c['name']}</b>", c['pos'], k(c['budget']), f"{paid:,}".replace(',', ' '), f"{c['free']:,}".replace(',', ' '), f"${mrr//1000}k", f"${c['price']}", c['goal']])
seg_rows = [[s['name'], f"{s['size']:,}".replace(',', ' '), f"${s['wtp']}", f"{round(s['base_paid']*100)} из 100", s['where'], s['values']] for s in SEGMENTS]
def rng(v): return 'не работает' if v is None else f'${v[0]}-{v[1]}'
ch_rows = [[c['name'], k(c['min_k']*1000)] + [rng(c['cpu'][s['id']]) for s in SEGMENTS] + [c['when'], c['risk']] for c in CHANNELS]
act_rows = [[a['name'], a['cost'], a['effect'], a['chance'], a['risk']] for a in ACTIONS]

